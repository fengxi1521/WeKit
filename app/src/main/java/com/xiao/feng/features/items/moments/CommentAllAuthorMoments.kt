/**
 * Adds a "comment on all their Moments" entry to the long-press menu of a Moment: every cached
 * Moment owned by that author is commented, including pinned posts, while posts we already
 * commented on, deleted posts, and advertisements are skipped.
 *
 * Comments can either be generated by the AI configuration of [AutoCommentMoments] or reuse its
 * fixed comment text. Comments posted here are registered with [AutoCommentMoments] so the AI
 * reply engine still recognises and answers replies to them.
 */
object CommentAllAuthorMoments : ClickableFeature(), WeMomentsContextMenuApi.IMenuItemsProvider {

    override val technicalId = "一键评论作者全部朋友圈"
    override val nameRes = R.string.feature_comment_all_author_moments_name
    override val categoryIds = listOf(FeatureCategoryIds.MOMENTS)
    override val descriptionRes = R.string.feature_comment_all_author_moments_description
    override val defaultEnabled = true

    private const val TAG = "CommentAllAuthorMoments"

    /** 相邻两条评论之间的等待时间 (毫秒); AI 生成本身也要时间, 0 表示不额外等待。 */
    private const val KEY_DELAY_MS = "comment_all_author_delay_ms"
    private const val DEFAULT_DELAY_MS = 2_000L
    private const val MAX_DELAY_MS = 120_000L

    /** 是否用 AI 生成评论; 关闭时使用「朋友圈自动评论」里的固定评论内容。 */
    private const val KEY_USE_AI = "comment_all_author_use_ai"

    var delayMs: String by prefOption(KEY_DELAY_MS, DEFAULT_DELAY_MS.toString())
    private var useAi by prefOption(KEY_USE_AI, true)

    private val runningOwners = ConcurrentHashMap.newKeySet<String>()

    private data class CommentSummary(val commented: Int, val skipped: Int, val failed: Int)

    override fun onClick(context: ComponentActivity) {
        showComposeDialog(context) {
            var delayInput by remember { mutableStateOf(delayMs) }
            var aiInput by remember { mutableStateOf(useAi) }
            AlertDialogContent(
                title = { Text(stringResource(R.string.moments_comment_all_author_settings_title)) },
                text = {
                    Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                        SegmentedColumn(contentPadding = PaddingValues(0.dp)) {
                            item {
                                SwitchWidget(
                                    title = stringResource(R.string.moments_comment_all_author_ai_title),
                                    description = stringResource(R.string.moments_comment_all_author_ai_description),
                                    checked = aiInput,
                                    onCheckedChange = {
                                        aiInput = it
                                        useAi = it
                                    },
                                )
                            }
                            item {
                                BaseWidget(
                                    title = stringResource(R.string.moments_comment_all_author_clear_cache),
                                    description = stringResource(R.string.moments_comment_all_author_clear_cache_description),
                                    isError = true,
                                    onClick = {
                                        AutoCommentMoments.clearAiCaches()
                                        showToast(
                                            context,
                                            context.localizedMomentsString(R.string.moments_comment_all_author_clear_cache_done),
                                        )
                                    },
                                )
                            }
                        }
                        OutlinedTextField(
                            value = delayInput,
                            onValueChange = { delayInput = it.filter(Char::isDigit).take(6) },
                            label = { Text(stringResource(R.string.moments_comment_all_author_delay_ms)) },
                            supportingText = {
                                Text(stringResource(R.string.moments_comment_all_author_delay_description))
                            },
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                            singleLine = true,
                            modifier = Modifier.fillMaxWidth(),
                        )
                    }
                },
                confirmButton = {
                    Button(onClick = {
                        delayMs = delayInput
                        onDismiss()
                    }) { Text(stringResource(R.string.dialog_confirm)) }
                },
                dismissButton = {
                    TextButton(onClick = onDismiss) { Text(stringResource(R.string.dialog_cancel)) }
                },
            )
        }
    }

    override fun onEnable() {
        WeMomentsContextMenuApi.addProvider(this)
    }

    override fun onDisable() {
        WeMomentsContextMenuApi.removeProvider(this)
        runningOwners.clear()
    }

    override fun getMenuItems(): List<WeMomentsContextMenuApi.MenuItem> {
        return listOf(
            WeMomentsContextMenuApi.MenuItem(
                777022,
                localizedMomentsString(R.string.moments_comment_all_author_menu),
                ChatInfoIcon,
                { context, _ ->
                    val owner = WeMomentsApi.getOwnerWxId(context)
                    !owner.isNullOrEmpty() && owner != WeApi.selfWxId
                },
            ) { context ->
                commentAllMomentsOfOwner(context)
            }
        )
    }

    private fun commentAllMomentsOfOwner(context: WeMomentsContextMenuApi.MomentsContext) {
        val activity = context.activity
        val owner = WeMomentsApi.getOwnerWxId(context)
        if (owner.isNullOrEmpty()) {
            WeLogger.w(TAG, "failed to resolve the Moments author")
            return
        }
        val notConfigured = if (useAi) {
            AutoCommentMoments.aiConfig().apiKey.isBlank()
        } else {
            AutoCommentMoments.fixedCommentText().isBlank()
        }
        if (notConfigured) {
            CoroutineScope(Dispatchers.Main).launch {
                showToastSuspend(
                    activity,
                    activity.localizedMomentsString(R.string.moments_comment_all_author_not_configured),
                )
            }
            return
        }
        if (!runningOwners.add(owner)) {
            CoroutineScope(Dispatchers.Main).launch {
                showToastSuspend(activity, activity.localizedMomentsString(R.string.moments_comment_all_author_running))
            }
            return
        }

        CoroutineScope(Dispatchers.Main).launch {
            try {
                showToastSuspend(activity, activity.localizedMomentsString(R.string.moments_comment_all_author_started))
                val summary = withContext(Dispatchers.IO) {
                    runCatching { commentAllMoments(owner) }
                        .onFailure { WeLogger.w(TAG, "failed to comment all Moments of $owner", it) }
                        .getOrNull()
                }
                when {
                    summary == null -> showToastSuspend(
                        activity,
                        activity.localizedMomentsString(R.string.moments_comment_all_author_failed),
                    )

                    summary.commented + summary.skipped == 0 -> showToastSuspend(
                        activity,
                        activity.localizedMomentsString(R.string.moments_comment_all_author_empty),
                    )

                    else -> showToastSuspend(
                        activity,
                        activity.localizedMomentsString(
                            R.string.moments_comment_all_author_done,
                            summary.commented,
                            summary.skipped,
                            summary.failed,
                        ),
                    )
                }
            } finally {
                runningOwners.remove(owner)
            }
        }
    }

    private suspend fun commentAllMoments(owner: String): CommentSummary {
        val aiConfig = if (useAi) AutoCommentMoments.aiConfig() else null
        val fixedText = AutoCommentMoments.fixedCommentText().trim()

        var commented = 0
        var skipped = 0
        var failed = 0

        val seen = mutableSetOf<String>()
        for (snsInfo in collectOwnedSnsInfos(owner)) {
            val tableId = WeMomentsApi.getSnsTableId(snsInfo) ?: continue
            // A pinned Moment is also cached in the SnsInfo table on some hosts; comment once.
            if (!seen.add(tableId)) continue

            if (WeMomentsApi.isDeleted(snsInfo) || WeMomentsApi.isAd(snsInfo)) {
                skipped++
                continue
            }
            val snsId = WeMomentsApi.getSnsIdLong(snsInfo)
            if (snsId != null && hasOwnComment(snsId)) {
                skipped++
                continue
            }

            val text = if (aiConfig != null) {
                AutoCommentAi.generate(snsInfo, aiConfig)
            } else {
                fixedText.ifBlank { null }
            }
            if (text.isNullOrBlank()) {
                failed++
                continue
            }

            val result = WeMomentsApi.comment(snsInfo, text)
            if (!result.success) {
                failed++
                continue
            }
            commented++
            // 让 AI 回复仍能认出这条评论, 并避免自动评论对同一条朋友圈再发一次。
            if (snsId != null) AutoCommentMoments.rememberPostedComment(snsId.toString(), text)
            AutoCommentMoments.markCommentHandled(tableId)
            delay(commentDelayMillis())
        }

        WeLogger.i(TAG, "comment all Moments of $owner: commented=$commented skipped=$skipped failed=$failed")
        return CommentSummary(commented, skipped, failed)
    }

    private fun commentDelayMillis(): Long =
        (delayMs.toLongOrNull() ?: DEFAULT_DELAY_MS).coerceIn(0L, MAX_DELAY_MS)

    private fun hasOwnComment(snsId: Long): Boolean =
        WeMomentsApi.rawQuerySnsInfo(
            "SELECT 1 FROM SnsComment WHERE snsID = ? AND isSend = 1 LIMIT 1",
            arrayOf(snsId.toString()),
        ).use { it.moveToFirst() }

    /**
     * Pinned Moments live in the host's star storage rather than the SnsInfo table (the latter
     * only yields regular posts), so both sources have to be merged here.
     */
    private fun collectOwnedSnsInfos(owner: String): List<Any> =
        queryOwnedSnsIds(owner).mapNotNull { WeMomentsApi.getSnsInfoBySnsId(it) } +
                WeMomentsApi.getPinnedSnsInfos(owner)

    /** Enumerates the author's regular posts from the local SnsInfo cache. */
    private fun queryOwnedSnsIds(owner: String): List<Long> {
        val sql = """
            SELECT snsId FROM SnsInfo
            WHERE userName = ?
              AND snsId != 0
              AND (sourceType & ${WeMomentsApi.ACTIVE_SOURCE_MASK}) != 0
              AND (sourceType & ${WeMomentsApi.AD_SOURCE_FLAG}) = 0
            ORDER BY createTime DESC
        """.trimIndent()

        val snsIds = mutableListOf<Long>()
        WeMomentsApi.rawQuerySnsInfo(sql, arrayOf(owner)).use { cursor ->
            while (cursor.moveToNext()) {
                snsIds += cursor.getLong(0)
            }
        }
        return snsIds
    }
}
